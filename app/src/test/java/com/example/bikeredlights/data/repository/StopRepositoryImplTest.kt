    @Test
    fun `getStopsByRideId maps entities to domain models correctly`() = runTest {
        // Given: DAO returns list of entities
        val entities = listOf(
            StopEntity(
                id = 1L,
                rideId = testRideId,
                stopNumber = 1,
                latitude = testLatitude,
                longitude = testLongitude,
                startTimestamp = testStartTime,
                endTimestamp = testEndTime,
                durationSeconds = testDurationSeconds,
                clusterId = null
            ),
            StopEntity(
                id = 2L,
                rideId = testRideId,
                stopNumber = 2,
                latitude = 46.2050,
                longitude = 6.1440,
                startTimestamp = testStartTime + 30000,
                endTimestamp = null,
                durationSeconds = null,
                clusterId = null
            )
        )

        coEvery { mockStopDao.getStopsByRideId(testRideId) } returns entities

        // When: Get stops by ride ID
        val result = repository.getStopsByRideId(testRideId)

        // Then: Entities correctly mapped to domain models
        assertEquals(2, result.size)

        // Stop 1 (ended)
        with(result[0]) {
            assertEquals(1L, id)
            assertEquals(testRideId, rideId)
            assertEquals(1, stopNumber)
            assertEquals(testLatitude, latitude, 0.0001)
            assertEquals(testLongitude, longitude, 0.0001)
            assertEquals(testStartTime, startTimestamp)
            assertEquals(testEndTime, endTimestamp)
            assertEquals(testDurationSeconds, durationSeconds)
            assertNull(clusterId)
        }

        // Stop 2 (active)
        with(result[1]) {
            assertEquals(2L, id)
            assertEquals(testRideId, rideId)
            assertEquals(2, stopNumber)
            assertNull(endTimestamp)
            assertNull(durationSeconds)
        }

        coVerify(exactly = 1) { mockStopDao.getStopsByRideId(testRideId) }
    }

