/**
 * Unit tests for StopRepositoryImpl (Feature 009, Phase 2, Task T014).
 *
 * Test Strategy:
 * - Mock StopDao to isolate repository logic from database
 * - Verify correct entity/model mapping between layers
 * - Verify DAO methods are called with correct parameters
 * - Test all repository methods defined in StopRepository interface
 *
 * Coverage:
 * - insertStop: Domain model → Entity mapping + DAO delegation
 * - updateStopEnd: DAO parameter forwarding
 * - getStopsByRideId: Entity list → Domain model list mapping
 * - getStopCountByRideId: Flow<Int> delegation (no mapping)
 * - getUnclusteredStops: Entity list → Domain model list mapping
 * - updateStopCluster: DAO parameter forwarding
 * - getStopById: Entity → Domain model mapping (with null handling)
 * - deleteStopsByRideId: DAO delegation
 *
 * Mocking Framework: MockK (Kotlin-first, better coroutine support than Mockito)
 *
 * Test Patterns:
 * - Use runTest { } for suspending functions
 * - Use coEvery/coVerify for suspend mocking/verification
 * - Use every/verify for regular function mocking/verification
 * - Clear mocks after each test to prevent state leakage
 */
class StopRepositoryImplTest {

    // Mock DAO (data layer dependency)
    private lateinit var mockStopDao: StopDao

    // System under test
    private lateinit var repository: StopRepositoryImpl

    // Test data fixtures
    private val testRideId = 1L
    private val testStopId = 42L
    private val testLatitude = 46.2044
    private val testLongitude = 6.1432
    private val testStartTime = 1000000L
    private val testEndTime = 1020000L
    private val testDurationSeconds = 20

    @Before
    fun setup() {
        mockStopDao = mockk()
        repository = StopRepositoryImpl(mockStopDao)
    }

    @After
    fun teardown() {
        clearAllMocks()
    }

    // ============================================================================
    // INSERT TESTS (Domain Model → Entity Mapping + DAO Delegation)
    // ============================================================================

    @Test
    fun `insertStop maps domain model to entity and delegates to DAO`() = runTest {
        // Given: Domain model for active stop (no endTimestamp/duration)
        val domainStop = Stop(
            id = 0L,  // Unsaved (will be generated by database)
            rideId = testRideId,
            stopNumber = 1,
            latitude = testLatitude,
            longitude = testLongitude,
            startTimestamp = testStartTime,
            endTimestamp = null,
            durationSeconds = null,
            clusterId = null
        )

        val expectedEntity = StopEntity(
            id = 0L,
            rideId = testRideId,
            stopNumber = 1,
            latitude = testLatitude,
            longitude = testLongitude,
            startTimestamp = testStartTime,
            endTimestamp = null,
            durationSeconds = null,
            clusterId = null
        )

        coEvery { mockStopDao.insertStop(expectedEntity) } returns testStopId

        // When: Insert stop via repository
        val result = repository.insertStop(domainStop)

        // Then: Returns DAO-generated ID
        assertEquals(testStopId, result)

        // Verify DAO called with correctly mapped entity
        coVerify(exactly = 1) { mockStopDao.insertStop(expectedEntity) }
    }

